import assert from 'node:assert/strict';
import {defaultSolarCatalog,sizeSolar,validateSolarCatalog} from '../shared/solar';
import {planDefinitions,validatePlan} from '../shared/service-plans';

const answers={goal:'Backup during power outages',battery:'Lithium',totalWatts:'1000',dailyHours:'6',backup:'4',headroom:'20'};
const sized=sizeSolar(answers,defaultSolarCatalog);
assert.equal(sized.ready,true);
if(!sized.ready)throw Error('Expected sizing');
assert.equal(sized.designWatts,1200);
assert.ok(sized.inverter.watts!>=1200);
assert.ok(sized.inverter.surgeWatts!>=sized.requiredSurge);
assert.ok(sized.inverter.maxPvWatts!>=sized.panelWatts);
assert.ok(sized.nominalBatteryKwh*.8*.9>=4*1.2);
assert.ok(sized.panelWatts*4*.75>=6000*1.2+4000*1.2/.9);
assert.equal(sized.calculation.hasUnpriced,true);
assert.equal(sized.calculation.lines.find(line=>line.id==='solar-rail')!.quantity,sized.panelCount*2);
const higher=sizeSolar({...answers,headroom:'40'},defaultSolarCatalog);
assert.ok(higher.ready&&higher.designWatts===1400);
const tubular=sizeSolar({...answers,battery:'Tubular'},defaultSolarCatalog);
assert.ok(tubular.ready&&tubular.batteryCount%4===0&&tubular.nominalBatteryKwh*.5*.9>=4*1.2);
const offGrid=sizeSolar({...answers,goal:'Off-grid power',backup:'48'},defaultSolarCatalog);
assert.ok(offGrid.ready&&offGrid.requiredBatteryKwh> sized.requiredBatteryKwh);
const prices=structuredClone(defaultSolarCatalog);
for(const part of [...prices.inverters,...prices.lithium,...prices.tubular,prices.panel,...prices.accessories])part.price=100;
const priced=sizeSolar(answers,prices);
assert.ok(priced.ready&&!priced.calculation.hasUnpriced);
assert.equal(priced.calculation.subtotal,priced.calculation.lines.reduce((sum,line)=>sum+line.quantity*100,0));
assert.equal(sizeSolar({...answers,totalWatts:'100000'},defaultSolarCatalog).ready,false);
assert.equal(sizeSolar({backup:'4',load0qty:'2',load0hours:'4'},defaultSolarCatalog).ready,false);
assert.throws(()=>validateSolarCatalog({...prices,headroom:19}));
assert.throws(()=>sizeSolar({...answers,backup:'-1'},prices));
const legacyAnswers=Object.fromEntries(planDefinitions.solar.fields.slice(0,24).map(field=>[field.key,field.options?.[0]??'']));
assert.equal(validatePlan({service:'solar',answers:legacyAnswers,notes:''}).answers.battery,'Lithium');
console.log('PASS: headroom, inverter and PV capacity, battery capacity/current, tubular strings, off-grid autonomy, prices and legacy plans.');
