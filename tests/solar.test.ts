import assert from 'node:assert/strict';
import {defaultSolarCatalog,sizeSolar,validateSolarCatalog} from '../shared/solar';
import {planDefinitions,validatePlan} from '../shared/service-plans';

const answers={goal:'Backup during power outages',battery:'Lithium',totalWatts:'1000',dailyHours:'6',backup:'4',headroom:'20'};
const sized=sizeSolar(answers,defaultSolarCatalog);
assert.equal(sized.ready,true);
if(!sized.ready)throw Error('Expected sizing');
assert.equal(sized.designWatts,1200);
assert.equal(sized.inverter.watts,2000);
assert.equal(sized.requiredSurge,1200);
assert.ok(sized.inverter.watts!>=1200);
assert.ok(sized.inverter.surgeWatts!>=sized.requiredSurge);
assert.ok(sized.reviewReasons.some(reason=>reason.includes('PV input power limit')));
assert.ok(sized.nominalBatteryKwh*.8*.96>=4*1.2);
const expectedBackupPvWh=(2000+4000/.92)*1.2/.96;
assert.ok(Math.abs(sized.pvEnergyWh-expectedBackupPvWh)<.000001);
assert.equal(sized.panelCount,Math.ceil(expectedBackupPvWh/(4*.86*550)));
assert.ok(sized.pvEnergyWh<(6000+4000/.92)*1.2/.96);
assert.equal(sized.calculation.hasUnpriced,true);
assert.equal(sized.calculation.lines.find(line=>line.id==='solar-rail')!.quantity,sized.panelCount*2);
const higher=sizeSolar({...answers,headroom:'40'},defaultSolarCatalog);
assert.ok(higher.ready&&higher.designWatts===1400);
const tubular=sizeSolar({...answers,battery:'Tubular'},defaultSolarCatalog);
assert.ok(tubular.ready&&tubular.batteryCount%4===0&&tubular.nominalBatteryKwh*.5*.96>=4*1.2);
assert.ok(tubular.ready&&tubular.batteryCount===8);
const offGrid=sizeSolar({...answers,goal:'Off-grid power',nightWatts:'250',nightHours:'8'},defaultSolarCatalog);
assert.ok(offGrid.ready);
if(!offGrid.ready)throw Error('Expected off-grid sizing');
assert.equal(offGrid.nightKwh,2);
assert.equal(offGrid.daytimeKwh,4);
assert.ok(Math.abs(offGrid.requiredBatteryKwh-2*1.2/.96/.8)<.00001);
assert.ok(Math.abs(offGrid.pvEnergyWh-(4000+2000/.92)*1.2/.96)<.00001);
assert.equal(offGrid.panelCount,Math.ceil((4000+2000/.92)*1.2/.96/(4*.86*550)));
assert.ok(offGrid.requiredBatteryKwh<sized.requiredBatteryKwh);
const nightTubular=sizeSolar({...answers,goal:'Off-grid power',battery:'Tubular',nightWatts:'250',nightHours:'8'},defaultSolarCatalog);
assert.ok(nightTubular.ready&&nightTubular.batteryCount===4);
const dayOnly=sizeSolar({...answers,goal:'Off-grid power',nightWatts:'0',nightHours:'8'},defaultSolarCatalog);
assert.ok(dayOnly.ready&&dayOnly.batteryCount===0&&dayOnly.calculation.lines.every(line=>line.quantity>0));
assert.equal(sizeSolar({...answers,goal:'Off-grid power',nightHours:'8',nightWatts:'1000'},defaultSolarCatalog).ready,false);
assert.equal(sizeSolar({...answers,goal:'Off-grid power'},defaultSolarCatalog).ready,false);
const prices=structuredClone(defaultSolarCatalog);
for(const part of [...prices.inverters,...prices.lithium,...prices.tubular,prices.panel,...prices.accessories])part.price=100;
const priced=sizeSolar(answers,prices);
assert.ok(priced.ready&&!priced.calculation.hasUnpriced);
assert.equal(priced.calculation.subtotal,priced.calculation.lines.reduce((sum,line)=>sum+line.quantity*100,0));
const surge=sizeSolar({...answers,surgeWatts:'5000'},prices);
assert.ok(surge.ready&&surge.requiredSurge===5000&&surge.inverter.surgeWatts!>=5000);
const limitedPv=structuredClone(prices);
limitedPv.inverters.find(inverter=>inverter.watts===2000)!.maxPvWatts=1000;
const needsController=sizeSolar(answers,limitedPv);
assert.ok(needsController.ready&&needsController.inverter.watts===2000&&needsController.calculation.hasUnpriced);
assert.ok(needsController.calculation.lines.some(line=>line.id==='solar-additional-mppt'&&line.unitPrice===null));
const longBackup=sizeSolar({...answers,backup:'24',rechargeDays:'3'},prices);
assert.ok(longBackup.ready);
if(longBackup.ready){
 assert.ok(Math.abs(longBackup.pvEnergyWh-(8000/.92)*1.2/.96)<.00001);
}
const alternatives=structuredClone(prices);
alternatives.lithium.push({...alternatives.lithium[0],id:'solar-lithium-large',name:'Test larger module',kwh:10,price:150});
const lowerCostBank=sizeSolar(answers,alternatives);
assert.ok(lowerCostBank.ready&&lowerCostBank.battery.id==='solar-lithium-large');
const legacyCatalog=structuredClone(prices);
delete legacyCatalog.lithiumRoundTrip;
delete legacyCatalog.tubularRoundTrip;
assert.equal(validateSolarCatalog(legacyCatalog).lithiumRoundTrip,.92);
const cycling=sizeSolar({load3qty:'1',load3watts:'200',load3hours:'24',dailyKwh:'1',backup:'4',battery:'Lithium'},prices);
assert.ok(cycling.ready&&cycling.dailyKwh===1&&cycling.runningWatts===200);
const metered=sizeSolar({...answers,dailyHours:'',dailyKwh:'6'},prices);
assert.ok(metered.ready&&metered.dailyKwh===6);
assert.throws(()=>sizeSolar({...answers,dailyKwh:'25'},prices));
assert.equal(sizeSolar({...answers,totalWatts:'100000'},defaultSolarCatalog).ready,false);
assert.equal(sizeSolar({backup:'4',load0qty:'2',load0hours:'4'},defaultSolarCatalog).ready,false);
assert.equal(sizeSolar({...answers,load0qty:'2',load0watts:'',load0hours:''},defaultSolarCatalog).ready,true);
assert.throws(()=>validateSolarCatalog({...prices,headroom:19}));
assert.throws(()=>sizeSolar({...answers,backup:'-1'},prices));
const legacyAnswers=Object.fromEntries(planDefinitions.solar.fields.slice(0,24).map(field=>[field.key,field.options?.[0]??'']));
assert.equal(validatePlan({service:'solar',answers:legacyAnswers,notes:''}).answers.battery,'Lithium');
assert.equal(validatePlan({service:'solar',answers:legacyAnswers,notes:''}).answers.panelWattage,'550 W');
const panelPrices=structuredClone(prices);
panelPrices.panel625!.price=150;
const largerPanels=sizeSolar({...answers,panelWattage:'625 W'},panelPrices);
assert.ok(largerPanels.ready);
if(largerPanels.ready){
 assert.equal(largerPanels.panelCount,Math.ceil(sized.requiredPvWatts/625));
 assert.equal(largerPanels.panelWatts,largerPanels.panelCount*625);
 assert.equal(largerPanels.requiredPvWatts,sized.requiredPvWatts);
 assert.equal(largerPanels.batteryCount,sized.batteryCount);
 assert.equal(largerPanels.calculation.lines.find(line=>line.id==='solar-panel-625')!.unitPrice,150);
 assert.ok(!largerPanels.calculation.lines.some(line=>line.id==='solar-panel'));
 assert.equal(largerPanels.calculation.lines.find(line=>line.id==='solar-rail')!.quantity,largerPanels.panelCount*2);
}
const oldPanels=structuredClone(prices);
delete oldPanels.panel625;
assert.equal(validateSolarCatalog(oldPanels).panel.price,100);
assert.equal(validateSolarCatalog(oldPanels).panel625!.price,null);
assert.throws(()=>sizeSolar({...answers,panelWattage:'700 W'},prices));
console.log('PASS: headroom, inverter and PV capacity, battery capacity/current, tubular strings, off-grid autonomy, prices and legacy plans.');
